#!/usr/bin/env python3
# gen-boot-splash.py — rasterize the boot splash PNG into an LVGL ARGB8888
# image sized for the 2×8 content grid (240×280 on the fnk0104 240×320 panel)
# and emit firmware/main/boot_splash.{c,h}.
#
#   python3 scripts/build/gen-boot-splash.py [path/to/source.png]
#
# Default source: scripts/build/assets/boot-splash.png
import os
import sys
try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow not installed — pip install Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(HERE, "assets", "boot-splash.png")
OUT_C = os.path.join(HERE, "..", "..", "firmware", "main", "boot_splash.c")
OUT_H = os.path.join(HERE, "..", "..", "firmware", "main", "boot_splash.h")

# 2 cols × 8 rows on 240×320: content_h = 320 - 20 - 16 = 284, cell_h = 35
BOOT_W = 240
BOOT_H = 280


def rgba_to_argb8888(rgba):
    pixels = list(rgba.getdata())
    out = []
    for r, g, b, a in pixels:
        out.extend([b, g, r, a])
    return out


def fit_image(path):
    im = Image.open(path).convert("RGBA")
    im.thumbnail((BOOT_W, BOOT_H), Image.LANCZOS)
    canvas = Image.new("RGBA", (BOOT_W, BOOT_H), (0, 0, 0, 0))
    canvas.paste(im, ((BOOT_W - im.width) // 2, (BOOT_H - im.height) // 2), im)
    return canvas


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    if not os.path.isfile(src):
        sys.exit(f"missing source image: {src}")
    rgba = fit_image(src)
    data = rgba_to_argb8888(rgba)
    stride = BOOT_W * 4
    n = BOOT_W * BOOT_H * 4

    rows = []
    for r in range(BOOT_H):
        row = data[r * stride:(r + 1) * stride]
        rows.append("    " + ",".join(str(v) for v in row) + ",")

    c = [
        "// AUTO-GENERATED by scripts/build/gen-boot-splash.py — do not edit.",
        '#include "boot_splash.h"',
        '#include "lvgl.h"',
        "",
        f"static const uint8_t boot_splash_map[{n}] = {{",
        *rows,
        "};",
        "",
        "const lv_image_dsc_t boot_splash_img = {",
        "    .header = { .magic = LV_IMAGE_HEADER_MAGIC,",
        "                .cf = LV_COLOR_FORMAT_ARGB8888,",
        f"                .w = {BOOT_W}, .h = {BOOT_H}, .stride = {stride} " + "},",
        f"    .data_size = {n}, .data = boot_splash_map,",
        "};",
        "",
    ]

    with open(OUT_C, "w") as f:
        f.write("\n".join(c))

    with open(OUT_H, "w") as f:
        f.write(
            "// AUTO-GENERATED by scripts/build/gen-boot-splash.py.\n"
            "#pragma once\n"
            "#include \"lvgl.h\"\n\n"
            "extern const lv_image_dsc_t boot_splash_img;\n"
        )

    print(f"wrote boot splash {BOOT_W}x{BOOT_H} -> {os.path.relpath(OUT_C, HERE + '/..')}")


if __name__ == "__main__":
    main()
